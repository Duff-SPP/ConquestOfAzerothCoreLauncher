const fs = require('node:fs/promises');
const path = require('node:path');
async function generateLocales() {
  const root = path.resolve(__dirname, '..');
  const languages = JSON.parse(await fs.readFile(path.join(root, 'localization/languages.json'), 'utf8'));
  const lines = ['// Generated by tools/generate-locales.cjs. Edit localization/*.json.'];
  for (const language of languages) {
    if (!/^[a-z]{2}(?:-[A-Z]{2})?$/.test(language.code)) throw new Error('Invalid language code.');
    const entries = JSON.parse(await fs.readFile(path.join(root, 'localization', language.code + '.json'), 'utf8'));
    lines.push(`launcherI18n.register(${JSON.stringify(language.code)}, ${JSON.stringify(language.name)}, ${JSON.stringify(entries, null, 2)}, ${language.complete === true});`);
  }
  await fs.writeFile(path.join(root, 'public/locales.js'), lines.join('\n') + '\n');
}
module.exports = generateLocales;
if (require.main === module) generateLocales().catch(error => { console.error(error.message); process.exitCode = 1; });
